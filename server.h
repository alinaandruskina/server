#pragma once
#include <string>
#include <map>
#include <fstream>
#include <csignal>
#include "auth.h"

/**
 * @file server.h
 * @brief Заголовочный файл основного класса сервера.
 * @details Содержит класс Server для реализации TCP-сервера с аутентификацией.
 */

/**
 * @struct Params
 * @brief Структура для хранения параметров сервера.
 * @details Содержит настройки порта, пути к файлам базы и логов.
 */
struct Params {
    int port;              ///< Номер порта для прослушивания.
    std::string auth_file; ///< Путь к файлу базы пользователей.
    std::string log_file;  ///< Путь к файлу журнала работы.
};

/**
 * @class Server
 * @brief Основной класс TCP-сервера.
 * @details Реализует логику приема соединений, аутентификации клиентов 
 * и обработки запросов на вычисление суммы векторов. Сервер работает 
 * в цикле, принимая подключения и обрабатывая их последовательно.
 * 
 * Протокол работы:
 * 1. Клиент отправляет логин
 * 2. Сервер генерирует соль и отправляет клиенту
 * 3. Клиент вычисляет хеш от соли и пароля, отправляет серверу
 * 4. Сервер проверяет хеш и отправляет OK или ERR
 * 5. При успехе клиент отправляет векторы, сервер возвращает суммы
 */
class Server {
private:
    Params params;              ///< Параметры сервера.
    Auth auth;                  ///< Объект для работы с аутентификацией.
    std::map<std::string, std::string> db; ///< База пользователей (логин:пароль).
    int server_socket;          ///< Дескриптор слушающего сокета.
    std::ofstream log_file;     ///< Файловый поток для записи логов.
    bool isRunning;             ///< Флаг работы сервера.
    bool isOverflow;            ///< Флаг переполнения при вычислении суммы.

    /**
     * @brief Записывает сообщение в консоль и лог-файл.
     * @param msg Текст сообщения для записи.
     */
    void writeLog(const std::string& msg);

    /**
     * @brief Загружает базу пользователей из файла.
     * @details Читает файл формата "логин:пароль" построчно.
     * Если файл не существует, создает файл по умолчанию.
     * @throw std::runtime_error Если файл не может быть открыт или создан.
     */
    void loadDatabase();

    /**
     * @brief Создает файл базы данных по умолчанию.
     * @details Записывает тестовых пользователей: user:P@ssW0rd и ibst128:SupErP@$$w0rd.
     */
    void createDefaultDatabase();

    /**
     * @brief Принимает строку от клиента.
     * @param client_sock Дескриптор сокета клиента.
     * @return std::string Принятая строка.
     * @throw std::runtime_error Если клиент отключился.
     */
    std::string recvString(int client_sock);

    /**
     * @brief Отправляет строку клиенту.
     * @param client_sock Дескриптор сокета клиента.
     * @param msg Строка для отправки.
     */
    void sendString(int client_sock, const std::string& msg);

    /**
     * @brief Вычисляет сумму элементов вектора.
     * @param arr Указатель на массив чисел.
     * @param size Размер массива.
     * @return double Сумма элементов.
     * @details При переполнении возвращает бесконечность и устанавливает флаг isOverflow.
     */
    double calculateSum(double* arr, int size);

    /**
     * @brief Выводит справку по использованию программы.
     * @details Показывает доступные параметры командной строки.
     */
    void printUsage();

public:
    /**
     * @brief Конструктор сервера.
     * @details Инициализирует параметры по умолчанию и регистрирует сервер как глобальный.
     */
    Server();

    /**
     * @brief Деструктор сервера.
     * @details Закрывает сокет и файл логов.
     */
    ~Server();

    /**
     * @brief Разбирает параметры командной строки.
     * @param argc Количество аргументов.
     * @param argv Массив аргументов.
     * @return true Если параметры корректны и сервер должен запуститься.
     * @return false Если запрошен вывод справки.
     * 
     * Поддерживаемые параметры:
     * - -h, --help: вывод справки
     * - -d, --db-file: путь к файлу базы
     * - -l, --log-file: путь к файлу логов
     * - -p, --port: номер порта
     */
    bool parseArgs(int argc, char** argv);

    /**
     * @brief Запускает сервер.
     * @details Создает сокет, привязывает к порту, начинает прослушивание 
     * и входит в цикл приема соединений.
     * @throw std::runtime_error При ошибках создания сокета или привязки.
     */
    void start();

    /**
     * @brief Останавливает сервер.
     * @details Устанавливает флаг isRunning в false и закрывает сокет.
     */
    void stop();
};
